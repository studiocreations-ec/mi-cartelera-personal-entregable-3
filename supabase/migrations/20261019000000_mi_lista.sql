create table if not exists public.mi_lista (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  tmdb_id integer not null check (tmdb_id > 0),
  titulo text not null check (char_length(titulo) between 1 and 500),
  poster_url text,
  tipo_contenido text not null check (tipo_contenido in ('pelicula','serie')),
  estado text not null default 'por_ver' check (estado in ('por_ver','viendo','vista')),
  calificacion_personal integer check (calificacion_personal between 1 and 5),
  comentario text check (char_length(comentario) <= 3000),
  fecha_agregado timestamptz not null default now(),
  sinopsis text not null default '',
  fecha_estreno text,
  calificacion_tmdb numeric(3,1) check (calificacion_tmdb between 0 and 10),
  constraint mi_lista_usuario_titulo_unico unique (user_id,tmdb_id,tipo_contenido)
);
create index if not exists mi_lista_user_fecha_idx on public.mi_lista (user_id,fecha_agregado desc);
alter table public.mi_lista enable row level security;
revoke all on public.mi_lista from anon;
grant select,insert,update,delete on public.mi_lista to authenticated;
grant usage,select on sequence public.mi_lista_id_seq to authenticated;
create policy "E1 leer solo mi lista" on public.mi_lista for select to authenticated using ((select auth.uid()) = user_id);
create policy "E1 insertar solo mi lista" on public.mi_lista for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "E1 actualizar solo mi lista" on public.mi_lista for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "E1 borrar solo mi lista" on public.mi_lista for delete to authenticated using ((select auth.uid()) = user_id);
